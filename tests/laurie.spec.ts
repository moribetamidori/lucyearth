import { test, expect } from '@playwright/test';

test.use({ channel: 'chrome' });

test('demo run completes and its journal survives a reload', async ({ page }) => {
  await page.goto(`${process.env.LAURIE_TEST_URL ?? 'http://127.0.0.1:3107'}/laurie`);
  await expect(page.getByText('SANDBOX', { exact: true })).toBeVisible();
  await expect(page.getByText('Recorded sample chart data · not live', { exact: false })).toBeVisible();
  const chart = page.getByRole('img', { name: /SPY .* candlestick chart/ });
  await expect(chart).toHaveAttribute('data-candle-count', '390');
  await page.getByLabel('Candle interval').selectOption('5m');
  await expect(chart).toHaveAttribute('aria-label', /5 minutes candlestick chart/);
  await expect(chart).toHaveAttribute('data-candle-count', '78');
  await page.getByLabel('Candle interval').selectOption('30m');
  await expect(chart).toHaveAttribute('data-candle-count', '13');
  await page.getByRole('button', { name: '1W', exact: true }).click();
  await expect(chart).toHaveAttribute('data-candle-count', '65');
  await page.getByLabel('Candle interval').selectOption('15m');
  await expect(chart).toHaveAttribute('data-candle-count', '130');
  await page.getByRole('button', { name: '3M', exact: true }).click();
  await expect(page.getByLabel('Candle interval')).toHaveValue('15m');
  await expect(chart).toHaveAttribute('data-candle-count', '1690');
  await page.getByLabel('Candle interval').selectOption('4h');
  await expect(chart).toHaveAttribute('data-candle-count', '130');
  await page.getByRole('button', { name: '5Y', exact: true }).click();
  await expect(page.getByLabel('Candle interval')).toHaveValue('4h');
  await expect(chart).toHaveAttribute('data-candle-count', '2');
  await page.getByRole('button', { name: 'MAX', exact: true }).click();
  await expect(page.getByLabel('Candle interval')).toHaveValue('4h');
  await expect(chart).toHaveAttribute('data-candle-count', '2');
  await page.getByRole('button', { name: '1D', exact: true }).click();
  await page.getByLabel('Candle interval').selectOption('1m');
  await page.getByRole('button', { name: 'Run Agent' }).click();
  await expect(page.getByText('No order · demo simulation').first()).toBeVisible();
  await expect(page.getByText('HOLD', { exact: true }).first()).toBeVisible();
  await expect(page.getByText('1 RUNS')).toBeVisible();
  await page.screenshot({ path: '/private/tmp/laurie-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Run Agent' })).toBeVisible();
  await page.screenshot({ path: '/private/tmp/laurie-mobile.png', fullPage: true });
  await page.reload();
  await expect(page.getByText('1 RUNS')).toBeVisible();
  await expect(page.getByText('No order · demo simulation').first()).toBeVisible();
  await page.getByRole('button', { name: 'Run Agent' }).click();
  await expect(page.getByText('2 RUNS')).toBeVisible();
  await page.getByRole('button', { name: /HOLD.*Demo simulation/ }).last().click();
  await expect(page.getByText('A result, with its reasoning')).toBeVisible();
  await expect(chart).toHaveAttribute('data-candle-count', '390');
});
